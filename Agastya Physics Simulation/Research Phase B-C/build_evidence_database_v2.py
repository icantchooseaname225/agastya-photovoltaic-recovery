def write_csv(filename: str, rows: list[dict[str, str]], fields: list[str] | None = None) -> None:
    selected_fields = fields or FIELDS
    with (ROOT / filename).open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=selected_fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


